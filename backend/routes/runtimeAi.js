"use strict";
const express = require('express');
const pool = require('../config/database');
const { authMiddleware } = require('../middleware/auth');
const { createRecommendationHandlers } = require('../services/runtimeRecommendation');
const router = express.Router();
const recommendation = createRecommendationHandlers({ pool });
router.post('/recommendation', authMiddleware, recommendation.generate);
router.get('/recommendation/history', authMiddleware, recommendation.history);
module.exports = router;
